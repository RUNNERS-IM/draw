let current =
  typeof window !== 'undefined' ? pick(window.electronAPI?.locale || navigator.language) : 'en'

function pick(language: string) {
  return String(language || '')
    .toLowerCase()
    .startsWith('ko')
    ? 'ko'
    : 'en'
}

export function setLocale(language: string) {
  current = pick(language)
}

export function currentLocale() {
  return current
}

export function t(key: string, vars?: Record<string, string | number>) {
  const text = messages[current][key] ?? messages.en[key] ?? key
  if (!vars) {
    return text
  }
  return text.replace(/\{(\w+)\}/g, (whole: string, name: string) =>
    name in vars ? String(vars[name]) : whole
  )
}

